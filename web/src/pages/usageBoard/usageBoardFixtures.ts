function percentWindow(
  id: string,
  percentUsed: number | null,
  state: string,
  timeLeft: number | null,
  extra: Partial<UsageWindowView> = {},
): UsageWindowView {
  return {
    id,
    kind: id === "7d" ? "weekly" : "session",
    label: id,
    group: null,
    percent_used: percentUsed,
    remaining_pct: percentUsed === null ? null : 100 - percentUsed,
    window_minutes: id === "7d" ? 10_080 : 300,
    resets_at: timeLeft === null ? null : NOW + timeLeft,
    time_left_s: timeLeft,
    pace_pct: percentUsed === null ? null : (100 - percentUsed) * 2,
    state,
    ahead_pts: null,
    used_value: null,
    limit_value: null,
    unit: null,
    past_reset: false,
    ...extra,
  };
}

